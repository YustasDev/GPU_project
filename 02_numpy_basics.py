import cv2
import numpy as np
from PIL import Image

if __name__ == "__main__":
    # прочитаем файл с растровым изображением и результат сохраним в переменную image
    image = cv2.imread('test2.jpg')

    # Тип данных (dtype)
    print(f"Тип данных: {image.dtype}")  # обычно uint8

    # Форма/размеры (shape)
    print(f"Размеры: {image.shape}")  # (высота, ширина, каналы)

    # Количество измерений
    print(f"Размерность: {image.ndim}")  # 2, 3 или 4

    # Для BGR: каналы идут в порядке [Blue, Green, Red]
    blue_channel = image[:, :, 0]  # Синий
    green_channel = image[:, :, 1]  # Зеленый
    red_channel = image[:, :, 2]  # Красный

    # двумерная матрица, где яркие области соответствуют местам с высоким содержанием красного цвета в оригинале.
    h, w = red_channel.shape    # h = 3072  w = 4080

    # ─────────────────────────────────────────────────────────────
    # 1. Красный круг
    # ─────────────────────────────────────────────────────────────
    # Параметры: изображение, центр, радиус, цвет, толщина линии
    cv2.circle(
        img=image,
        center=(2784, 2500),    # центр круга (x, y)
        radius=300,             # радиус в пикселях
        color=(0, 0, 255),      # красный в формате BGR
        thickness=7             # толщина линии (-1 = заливка)
    )

    # ─────────────────────────────────────────────────────────────
    # 2. Зеленый прямоугольник
    # ─────────────────────────────────────────────────────────────
    # Параметры: изображение, верхний-левый угол, нижний-правый угол, цвет, толщина
    cv2.rectangle(
        img=image,
        pt1=(1928, 2136),         # верхний левый угол
        pt2=(2224, 2464),         # нижний правый угол
        color=(0, 255, 0),        # зеленый в формате BGR
        thickness=7
    )

    # ─────────────────────────────────────────────────────────────
    # 3. Синий треугольник (полигон из 3 точек)
    # ─────────────────────────────────────────────────────────────
    # Определяем три вершины треугольника
    triangle_points = np.array([
        [440, 280],   # верхняя вершина
        [196, 712],    # левая нижняя
        [672, 712]    # правая нижняя
    ], dtype=np.int32)

    # Рисуем замкнутую фигуру
    cv2.polylines(
        img=image,
        pts=[triangle_points],  # список массивов точек
        isClosed=True,          # замкнуть фигуру
        color=(255, 0, 0),      # синий в формате BGR
        thickness=7
    )

    # ─────────────────────────────────────────────────────────────
    # 4. Текст на изображении
    # ─────────────────────────────────────────────────────────────
    # Параметры: изображение, текст, позиция, шрифт, масштаб, цвет, толщина
    cv2.putText(
        img=image,
        text='OpenCV Demo',                  # текст
        org=(184, 2844),                     # позиция (левый нижний угол текста)
        fontFace=cv2.FONT_HERSHEY_SIMPLEX,   # тип шрифта
        fontScale=3,                         # масштаб шрифта
        color=(0, 0, 0),                     # черный цвет (BGR)
        thickness=7,                         # толщина линий букв
        lineType=cv2.LINE_AA                 # сглаживание
    )

    # Добавим подписи к фигурам
    cv2.putText(image, 'Circle', (2664, 2860), cv2.FONT_HERSHEY_SIMPLEX, 2.5, (0, 0, 255), 5)
    cv2.putText(image, 'Rectangle', (1920, 2556), cv2.FONT_HERSHEY_SIMPLEX, 2.5, (0, 255, 0), 5)
    cv2.putText(image, 'Triangle', (252, 832), cv2.FONT_HERSHEY_SIMPLEX, 2.5, (255, 0, 0), 5)


    # ─────────────────────────────────────────────────────────────
    # Сохранение и отображение результата
    # ─────────────────────────────────────────────────────────────

    # преобразуем из матрицы BGR в матрицу RGB
    #image_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    # Сохраняем в файл
    cv2.imwrite('output_image.png', image)
    print("✅ Изображение сохранено как 'output_image.png'")

    # Сохраняем в файл с помощью библиотеки PIL (Pillow)
    pil_image = Image.fromarray(image)
    pil_image.save('pil_output_image.png')

